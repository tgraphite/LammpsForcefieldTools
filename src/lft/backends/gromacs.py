"""Deterministic GROMACS topology, coordinate, and audit-sidecar writer."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ..domain.parameters import ParameterSet
from ..domain.structure import Structure
from ..domain.units import (
    angle_kcal_to_gromacs,
    angstrom_to_nm,
    bond_kcal_to_gromacs,
    kcal_to_kj,
)
from ..io.serializers import dump_json
from ..topology.pbc import compute_winding


def write_gromacs(
    structure: Structure,
    params: ParameterSet,
    output_dir: str | Path,
    *,
    disclose_dir: str | Path | None = None,
    emit_image_map: bool = True,
) -> dict[str, Path]:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    if structure.cell is None:
        structure.add_warning(
            "GROMACS_COMPATIBILITY_BOX",
            "non-periodic source received a finite compatibility box because modern GROMACS requires Verlet with a box",
        )
    elif structure.cell.pbc != (True, True, True):
        structure.add_warning(
            "GROMACS_PARTIAL_PBC_COMPATIBILITY",
            "GROMACS writer uses a full compatibility box for a partial-PBC source; source pbc mask remains in the IR",
            pbc=list(structure.cell.pbc),
        )
    stem = structure.name
    itp = output_dir / f"{stem}.itp"
    top = output_dir / f"{stem}.top"
    gro = output_dir / f"{stem}.gro"
    mdp = output_dir / f"{stem}.mdp"
    itp.write_text(_itp_text(structure, params))
    top.write_text(_top_text(structure, itp.name))
    gro.write_text(_gro_text(structure))
    mdp.write_text(_mdp_text(structure))
    artifacts: dict[str, Path] = {"itp": itp, "top": top, "gro": gro, "mdp": mdp}
    if emit_image_map:
        image_dir = Path(disclose_dir) if disclose_dir is not None else output_dir
        image_dir.mkdir(parents=True, exist_ok=True)
        image_map = image_dir / "image_map.json"
        dump_json(_image_map(structure), image_map)
        artifacts["image_map"] = image_map
    return artifacts


def _itp_text(structure: Structure, params: ParameterSet) -> str:
    lines: list[str] = ["; Generated by lft; units: nm, kJ/mol, kJ/mol/nm^2", "", "[ atomtypes ]", "; name  at.num  mass  charge  ptype  sigma(nm)  epsilon(kJ/mol)"]
    for type_name, atom_type in sorted(params.atom_types.items()):
        lines.append(f"{type_name:<10s} {atom_type.atomic_number:4d} {atom_type.mass:10.5f} {0.0: .6f} A {angstrom_to_nm(atom_type.sigma): .8f} {kcal_to_kj(atom_type.epsilon): .8f} ; source={atom_type.source}")
    lines.extend(["", "[ moleculetype ]", "; name  nrexcl", f"{structure.name}  3", "", "[ atoms ]", "; nr type resnr residue atom cgnr charge mass"])
    for atom in structure.atoms:
        lines.append(f"{atom.index:5d} {atom.atom_type:<10s} {atom.residue_id:5d} {atom.residue_name:<6s} {atom.name:<6s} {atom.index:5d} {atom.charge: .10f} {atom.mass: .5f}")
    if structure.bonds:
        lines.extend(["", "[ bonds ]", "; i j funct r0(nm) k(kJ/mol/nm^2)"])
        for bond, bond_parameter in zip(structure.bonds, params.bond_parameters):
            lines.append(f"{bond.i:5d} {bond.j:5d} 1 {angstrom_to_nm(bond_parameter.r0): .8f} {bond_kcal_to_gromacs(bond_parameter.k): .8f} ; source={bond_parameter.source} image_shift={_shift(bond.image_shift)}")
    if structure.angles:
        lines.extend(["", "[ angles ]", "; i j k funct theta0(deg) k(kJ/mol/rad^2)"])
        for term, angle_parameter in zip(structure.angles, params.angle_parameters):
            lines.append(f"{term.atoms[0]:5d} {term.atoms[1]:5d} {term.atoms[2]:5d} 1 {angle_parameter.theta0: .6f} {angle_kcal_to_gromacs(angle_parameter.k): .8f} ; source={angle_parameter.source} images={_images(term.atom_images)}")
    if structure.dihedrals:
        lines.extend(["", "[ dihedrals ]", "; i j k l funct phase(deg) k(kJ/mol or kJ/mol/rad^2) periodicity"])
        for term, dihedral_parameter in zip(structure.dihedrals, params.dihedral_parameters):
            # GROMACS functype 9 is the proper periodic form.  A "harmonic"
            # dihedral (LAMMPS E=K[1+d cos(n phi)]) is the same function at
            # phase 0/180, and multi-term GAFF types are written as one line per
            # Fourier term (GROMACS sums them).
            terms = dihedral_parameter.fourier_terms()
            if dihedral_parameter.function == "harmonic" and not dihedral_parameter.terms:
                phase = 180.0 if abs((dihedral_parameter.phase % 360.0) - 180.0) < 1.0e-8 else 0.0
                terms = ((dihedral_parameter.k, dihedral_parameter.periodicity, phase),)
            for k_value, periodicity, phase in terms:
                coefficient = kcal_to_kj(k_value)
                lines.append(f"{term.atoms[0]:5d} {term.atoms[1]:5d} {term.atoms[2]:5d} {term.atoms[3]:5d} 9 {phase: .6f} {coefficient: .8f} {periodicity:d} ; source={dihedral_parameter.source} function={dihedral_parameter.function} images={_images(term.atom_images)}")
    if structure.impropers:
        lines.extend(["", "[ dihedrals ]", "; impropers: i j k l funct phase(deg) k(kJ/mol/rad^2)"])
        for term, improper_parameter in zip(structure.impropers, params.improper_parameters):
            coefficient = kcal_to_kj(improper_parameter.k)
            lines.append(f"{term.atoms[0]:5d} {term.atoms[1]:5d} {term.atoms[2]:5d} {term.atoms[3]:5d} 4 {improper_parameter.phase: .6f} {coefficient: .8f} {improper_parameter.periodicity:d} ; source={improper_parameter.source} images={_images(term.atom_images)}")
    if structure.pairs:
        lines.extend(["", "[ pairs ]", "; 1-4 pairs: i j funct (fudgeLJ/fudgeQQ applied via [ defaults ])"])
        for term in structure.pairs:
            lines.append(f"{term.atoms[0]:5d} {term.atoms[1]:5d} 1 ; images={_images(term.atom_images)}")
    lines.extend(["", "; 1-4 interactions are listed explicitly so GROMACS includes their", "; LJ/Coulomb in the total potential; periodic image lifts, when needed, are in <name>.lft/image_map.json"])
    return "\n".join(lines) + "\n"


def _top_text(structure: Structure, itp_name: str) -> str:
    return "\n".join([
        "; Generated by lft",
        "",
        "[ defaults ]",
        "; nbfunc comb-rule gen-pairs fudgeLJ fudgeQQ",
        "1 2 yes 0.5 0.8333333333",
        "",
        f'#include "{itp_name}"',
        "",
        "[ system ]",
        structure.name,
        "",
        "[ molecules ]",
        "; molecule nmols",
        f"{structure.name} 1",
        "",
    ])


def _gro_text(structure: Structure) -> str:
    lines = [structure.name, f"{structure.natoms:5d}"]
    for atom in structure.atoms:
        name = atom.name[-5:]
        residue = atom.residue_name[:5]
        lines.append(f"{atom.residue_id % 100000:5d}{residue:<5s}{name:>5s}{atom.index % 100000:5d}{angstrom_to_nm(atom.position[0]):8.3f}{angstrom_to_nm(atom.position[1]):8.3f}{angstrom_to_nm(atom.position[2]):8.3f}")
    if structure.cell is None:
        # Keep every box vector larger than twice the 1 nm short-range cutoff.
        low = structure.coordinates.min(axis=0) - 12.0
        high = structure.coordinates.max(axis=0) + 12.0
        span = (high - low) / 10.0
        lines.append(f"{span[0]:10.5f}{span[1]:10.5f}{span[2]:10.5f}")
    else:
        matrix = structure.cell.matrix / 10.0
        if _is_orthorhombic(matrix):
            lines.append(f"{matrix[0,0]:10.5f}{matrix[1,1]:10.5f}{matrix[2,2]:10.5f}")
        else:
            values = [matrix[0,0], matrix[1,1], matrix[2,2], matrix[1,0], matrix[2,0], matrix[0,1], matrix[2,1], matrix[0,2], matrix[1,2]]
            lines.append("".join(f"{value:10.5f}" for value in values))
    return "\n".join(lines) + "\n"


def _mdp_text(structure: Structure) -> str:
    # GROMACS 2020+ removed the group cutoff scheme and requires a finite box
    # for Verlet.  A non-periodic source therefore receives a compatibility
    # box in the .gro writer; the source IR remains non-periodic.
    pbc = "xyz"
    cutoff_scheme = "Verlet"
    if structure.cell is None:
        cutoff_nm = 1.0
    else:
        periodic_lengths = [
            float((structure.cell.matrix[:, index] ** 2).sum() ** 0.5) / 10.0
            for index, periodic in enumerate(structure.cell.pbc)
            if periodic
        ]
        cutoff_nm = min(1.0, 0.49 * min(periodic_lengths)) if periodic_lengths else 1.0
    return "\n".join([
        "integrator = md",
        "nsteps = 0",
        "dt = 0.001",
        f"pbc = {pbc}",
        "constraints = none",
        f"cutoff-scheme = {cutoff_scheme}",
        "coulombtype = Cut-off",
        "coulomb-modifier = None",
        f"rcoulomb = {cutoff_nm:.6f}",
        "vdwtype = Cut-off",
        "vdw-modifier = None",
        f"rvdw = {cutoff_nm:.6f}",
        f"rlist = {cutoff_nm:.6f}",
        "verlet-buffer-tolerance = -1",
        "nstlist = 10",
        "nstenergy = 1",
        "nstxout = 1",
        "continuation = yes",
        "",
    ])


def _image_map(structure: Structure) -> dict[str, Any]:
    def term_payload(term: Any) -> dict[str, Any]:
        positions = []
        for atom_index, image in zip(term.atoms, term.atom_images):
            position = structure.atom(atom_index).position.copy()
            if structure.cell is not None:
                position = position + structure.cell.image_vector(image)
            positions.append([float(value) for value in position])
        return {"atoms": list(term.atoms), "atom_images": [list(image) for image in term.atom_images], "local_positions_angstrom": positions}

    return {
        "schema": "lft.image_map.v1",
        "cell": structure.cell.to_dict() if structure.cell else None,
        "bonds": [{"atoms": [bond.i, bond.j], "image_shift": list(bond.image_shift), "order": bond.order} for bond in structure.bonds],
        "angles": [term_payload(term) for term in structure.angles],
        "dihedrals": [term_payload(term) for term in structure.dihedrals],
        "impropers": [term_payload(term) for term in structure.impropers],
        "pairs": [term_payload(term) for term in structure.pairs],
        "winding": compute_winding(structure),
    }


def _shift(shift: tuple[int, int, int]) -> str:
    return "(" + ",".join(str(value) for value in shift) + ")"


def _images(images: tuple[tuple[int, int, int], ...]) -> str:
    return "[" + ",".join(_shift(image) for image in images) + "]"


def _is_orthorhombic(matrix: Any) -> bool:
    return all(
        abs(float(matrix[i, j])) < 1.0e-10
        for i, j in ((0, 1), (0, 2), (1, 0), (1, 2), (2, 0), (2, 1))
    )
