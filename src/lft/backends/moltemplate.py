"""LAMMPS ``real`` data/in writer and moltemplate source writer."""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

from ..domain.parameters import ParameterSet
from ..domain.structure import Structure
from ..io.serializers import dump_json
from ..topology.pbc import compute_winding


def write_lammps(
    structure: Structure,
    params: ParameterSet,
    output_dir: str | Path,
    *,
    emit_lt: bool = False,
    disclose_dir: str | Path | None = None,
    emit_image_map: bool = True,
) -> dict[str, Path]:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    winding = compute_winding(structure)
    if winding["rank"]:
        structure.add_warning(
            "LAMMPS_PERIODIC_LIFT_SIDECAR",
            "periodic graph winding cannot be represented by one globally consistent atom-image assignment; image_map is authoritative for bonded lifts",
            winding_rank=winding["rank"],
        )
    stem = structure.name
    data = output_dir / f"{stem}.data"
    settings = output_dir / f"{stem}.in"
    data.write_text(_data_text(structure, params))
    settings.write_text(_input_text(structure, data.name, params))
    artifacts: dict[str, Path] = {"data": data, "input": settings}
    if emit_lt:
        lt = output_dir / f"{stem}.lt"
        lt.write_text(_lt_text(structure, params))
        system_lt = output_dir / "system.lt"
        system_lt.write_text(_system_lt_text(structure, stem))
        artifacts["lt"] = lt
        artifacts["system_lt"] = system_lt
    if emit_image_map:
        image_dir = Path(disclose_dir) if disclose_dir is not None else output_dir
        image_dir.mkdir(parents=True, exist_ok=True)
        image_map = image_dir / "image_map.json"
        dump_json(_image_map(structure), image_map)
        artifacts["image_map"] = image_map
    return artifacts


def _data_text(structure: Structure, params: ParameterSet) -> str:
    atom_type_ids = {
        name: index for index, name in enumerate(sorted(params.atom_types), start=1)
    }
    atom_types = sorted(params.atom_types)
    lines = [
        "LAMMPS data file generated by lft",
        "",
        f"{structure.natoms} atoms",
        f"{len(structure.bonds)} bonds",
        f"{len(structure.angles)} angles",
        f"{len(structure.dihedrals)} dihedrals",
        f"{len(structure.impropers)} impropers",
        "",
        f"{len(atom_types)} atom types",
        f"{len(params.bond_parameters)} bond types",
        f"{len(params.angle_parameters)} angle types",
        f"{len(params.dihedral_parameters)} dihedral types",
        f"{len(params.improper_parameters)} improper types",
        "",
    ]
    lines.extend(_box_lines(structure))
    lines.extend(["", "Masses", ""])
    for name in atom_types:
        lines.append(
            f"{atom_type_ids[name]} {params.atom_types[name].mass:.8f} # {name}"
        )
    lines.extend(["", "Pair Coeffs", ""])
    for name in atom_types:
        atom_type = params.atom_types[name]
        lines.append(
            f"{atom_type_ids[name]} {atom_type.epsilon:.10f} {atom_type.sigma:.10f} # {name}"
        )
    if params.bond_parameters:
        lines.extend(["", "Bond Coeffs", ""])
        for index, bond_parameter in enumerate(params.bond_parameters, start=1):
            lines.append(
                f"{index} {bond_parameter.k:.10f} {bond_parameter.r0:.10f} # source={bond_parameter.source}"
            )
    if params.angle_parameters:
        lines.extend(["", "Angle Coeffs", ""])
        for index, angle_parameter in enumerate(params.angle_parameters, start=1):
            lines.append(
                f"{index} {angle_parameter.k:.10f} {angle_parameter.theta0:.10f} # source={angle_parameter.source}"
            )
    if params.dihedral_parameters:
        lines.extend(["", "Dihedral Coeffs", ""])
        for index, dihedral_parameter in enumerate(params.dihedral_parameters, start=1):
            # Every proper dihedral uses the LAMMPS ``fourier`` form
            # E = K [1 + cos(n phi - delta)].  The historical UFF/periodic
            # placeholder (LAMMPS ``harmonic`` with d = +/-1) is exactly the
            # same function at phase 0 or 180 degrees, so no hybrid style and
            # no cross-engine formula discrepancy remain.
            phase = _periodic_phase(dihedral_parameter)
            lines.append(
                f"{index} 1 {dihedral_parameter.k:.10f} {dihedral_parameter.periodicity:d} {phase:.10f} # source={dihedral_parameter.source}"
            )
    if params.improper_parameters:
        lines.extend(["", "Improper Coeffs", ""])
        for index, improper_parameter in enumerate(params.improper_parameters, start=1):
            # CVFF uses K, sign, multiplicity rather than a degree phase.
            sign = 1 if abs(improper_parameter.phase) < 90.0 else -1
            lines.append(
                f"{index} {improper_parameter.k:.10f} {sign:d} {improper_parameter.periodicity:d} # source={improper_parameter.source}"
            )
    lines.extend(["", "Atoms # full", ""])
    positions = _lammps_positions(structure)
    for atom in structure.atoms:
        position, image = positions[atom.index]
        lines.append(
            f"{atom.index} {atom.molecule_id} {atom_type_ids[atom.atom_type or '']} {atom.charge:.12f} {position[0]:.10f} {position[1]:.10f} {position[2]:.10f} {image[0]} {image[1]} {image[2]}"
        )
    if structure.bonds:
        lines.extend(["", "Bonds", ""])
        for index, bond in enumerate(structure.bonds, start=1):
            lines.append(
                f"{index} {index} {bond.i} {bond.j} # image_shift={bond.image_shift}"
            )
    if structure.angles:
        lines.extend(["", "Angles", ""])
        for index, term in enumerate(structure.angles, start=1):
            lines.append(
                f"{index} {index} {' '.join(str(atom) for atom in term.atoms)}"
            )
    if structure.dihedrals:
        lines.extend(["", "Dihedrals", ""])
        for index, term in enumerate(structure.dihedrals, start=1):
            lines.append(
                f"{index} {index} {' '.join(str(atom) for atom in term.atoms)}"
            )
    if structure.impropers:
        lines.extend(["", "Impropers", ""])
        for index, term in enumerate(structure.impropers, start=1):
            lines.append(
                f"{index} {index} {' '.join(str(atom) for atom in term.atoms)}"
            )
    return "\n".join(lines) + "\n"


def _box_lines(structure: Structure) -> list[str]:
    if structure.cell is None:
        coordinates = structure.coordinates
        low = coordinates.min(axis=0) - 1.0
        high = coordinates.max(axis=0) + 1.0
        return [
            f"{low[0]:.10f} {high[0]:.10f} xlo xhi",
            f"{low[1]:.10f} {high[1]:.10f} ylo yhi",
            f"{low[2]:.10f} {high[2]:.10f} zlo zhi",
        ]
    matrix = structure.cell.matrix
    return [
        f"0.0 {matrix[0, 0]:.10f} xlo xhi",
        f"0.0 {matrix[1, 1]:.10f} ylo yhi",
        f"0.0 {matrix[2, 2]:.10f} zlo zhi",
        f"{matrix[0, 1]:.10f} {matrix[0, 2]:.10f} {matrix[1, 2]:.10f} xy xz yz",
    ]


def _lammps_positions(
    structure: Structure,
) -> dict[int, tuple[Any, tuple[int, int, int]]]:
    """Build wrapped coordinates and a spanning-tree-consistent image lift."""

    if structure.cell is None:
        return {atom.index: (atom.position, (0, 0, 0)) for atom in structure.atoms}
    graph_images = compute_winding(structure).get("atom_images", {})
    result: dict[int, tuple[Any, tuple[int, int, int]]] = {}
    for atom in structure.atoms:
        fractional = structure.cell.fractional(atom.position)
        base_image = [0, 0, 0]
        for index, periodic in enumerate(structure.cell.pbc):
            if periodic:
                base_image[index] = math.floor(float(fractional[index]) + 1.0e-10)
                fractional[index] -= base_image[index]
        graph_image = tuple(
            int(value) for value in graph_images.get(str(atom.index), (0, 0, 0))
        )
        image: tuple[int, int, int] = tuple(
            base_image[index] + graph_image[index] for index in range(3)
        )  # type: ignore[assignment]
        result[atom.index] = (structure.cell.cartesian(fractional), image)
    return result


def _periodic_phase(parameter: Any) -> float:
    """Map any proper-dihedral placeholder onto a 0/180 periodic phase."""

    if parameter.function == "harmonic":
        return 180.0 if abs((parameter.phase % 360.0) - 180.0) < 1.0e-8 else 0.0
    return float(parameter.phase)


def _input_text(structure: Structure, data_name: str, params: ParameterSet) -> str:
    boundary = (
        " ".join("p" if periodic else "f" for periodic in structure.cell.pbc)
        if structure.cell is not None
        else "f f f"
    )
    dihedral_style = "fourier"
    return "\n".join(
        [
            "# Generated by lft",
            "units real",
            "atom_style full",
            f"boundary {boundary}",
            "pair_style lj/cut/coul/cut 10.0",
            "pair_modify mix arithmetic",
            "bond_style harmonic",
            "angle_style harmonic",
            f"dihedral_style {dihedral_style}",
            "improper_style cvff",
            f"read_data {data_name}",
            "special_bonds lj 0.0 0.0 0.5 coul 0.0 0.0 0.8333333333",
            "neighbor 2.0 bin",
            "neigh_modify delay 0 every 1 check yes",
            "timestep 1.0",
            "thermo 1",
            "thermo_style custom step temp pe ebond eangle edihed eimp evdwl ecoul",
            "run 0",
            "",
        ]
    )


def _molecule_name(name: str) -> str:
    """Sanitize a structure name into a valid moltemplate molecule identifier."""

    cleaned = "".join(
        character if character.isalnum() else "_" for character in name.strip()
    )
    cleaned = cleaned.strip("_") or "MOL"
    if cleaned[0].isdigit():
        cleaned = f"M{cleaned}"
    return cleaned


def _lt_text(structure: Structure, params: ParameterSet) -> str:
    """Write the molecule template (one ``<name>`` molecule type).

    This follows the AuToFF convention: the ``.lt`` file defines a single
    molecule and a companion ``system.lt`` instantiates it and writes the
    boundary.  Keeping atom types as names (``@atom:c3``) and writing no image
    counters means moltemplate can replicate the molecule for packing.
    """

    atom_types = sorted(params.atom_types)
    molecule = _molecule_name(structure.name)
    boundary = (
        " ".join("p" if periodic else "f" for periodic in structure.cell.pbc)
        if structure.cell is not None
        else "f f f"
    )
    lines = [
        "# Generated by lft",
        "# Periodic image lifts, when needed, are in image_map.json",
        "",
        f"{molecule} {{",
    ]
    lines.extend(['  write("Data Atoms") {', "    # id mol type charge x y z"])
    positions = _lammps_positions(structure)
    for atom in structure.atoms:
        position, _image = positions[atom.index]
        # moltemplate currently rejects image-counter columns in Data Atoms;
        # the backend-independent image lift remains in image_map.json.
        lines.append(
            f"    $atom:{atom.index} $mol:{molecule} @atom:{atom.atom_type or ''} {atom.charge:.12f} {position[0]:.10f} {position[1]:.10f} {position[2]:.10f}"
        )
    lines.append("  }")
    lines.extend(['  write_once("Data Masses") {'])
    for name in atom_types:
        lines.append(f"    @atom:{name} {params.atom_types[name].mass:.8f}")
    lines.append("  }")
    lines.extend(['  write("Data Bonds") {'])
    for index, bond in enumerate(structure.bonds, start=1):
        lines.append(
            f"    $bond:{index} @bond:{index} $atom:{bond.i} $atom:{bond.j} # image_shift={bond.image_shift}"
        )
    lines.append("  }")
    if structure.angles:
        lines.append('  write("Data Angles") {')
        for index, term in enumerate(structure.angles, start=1):
            lines.append(
                f"    $angle:{index} @angle:{index} $atom:{term.atoms[0]} $atom:{term.atoms[1]} $atom:{term.atoms[2]}"
            )
        lines.append("  }")
    if structure.dihedrals:
        lines.append('  write("Data Dihedrals") {')
        for index, term in enumerate(structure.dihedrals, start=1):
            lines.append(
                f"    $dihedral:{index} @dihedral:{index} $atom:{term.atoms[0]} $atom:{term.atoms[1]} $atom:{term.atoms[2]} $atom:{term.atoms[3]}"
            )
        lines.append("  }")
    if structure.impropers:
        lines.append('  write("Data Impropers") {')
        for index, term in enumerate(structure.impropers, start=1):
            lines.append(
                f"    $improper:{index} @improper:{index} $atom:{term.atoms[0]} $atom:{term.atoms[1]} $atom:{term.atoms[2]} $atom:{term.atoms[3]}"
            )
        lines.append("  }")
    # Force-field *styles* live in "In Init" (moltemplate writes them to
    # ``system.in.init``); "In Settings" must contain only the ``*_coeff``
    # parameter commands so ``system.in.settings`` stays a pure coefficient file.
    lines.extend(
        [
            '  write_once("In Init") {',
            "    units real",
            "    atom_style full",
            f"    boundary {boundary}",
            "    pair_style lj/cut/coul/cut 10.0",
            "    pair_modify mix arithmetic",
            "    bond_style harmonic",
            "    angle_style harmonic",
            "    dihedral_style fourier",
            "    improper_style cvff",
            "    special_bonds lj 0.0 0.0 0.5 coul 0.0 0.0 0.8333333333",
            "  }",
            '  write_once("In Settings") {',
        ]
    )
    for index, bond_parameter in enumerate(params.bond_parameters, start=1):
        lines.append(
            f"    bond_coeff @bond:{index} {bond_parameter.k:.10f} {bond_parameter.r0:.10f}"
        )
    for index, angle_parameter in enumerate(params.angle_parameters, start=1):
        lines.append(
            f"    angle_coeff @angle:{index} {angle_parameter.k:.10f} {angle_parameter.theta0:.10f}"
        )
    for index, dihedral_parameter in enumerate(params.dihedral_parameters, start=1):
        phase = _periodic_phase(dihedral_parameter)
        lines.append(
            f"    dihedral_coeff @dihedral:{index} 1 {dihedral_parameter.k:.10f} {dihedral_parameter.periodicity:d} {phase:.10f}"
        )
    for index, improper_parameter in enumerate(params.improper_parameters, start=1):
        sign = 1 if abs(improper_parameter.phase) < 90.0 else -1
        lines.append(
            f"    improper_coeff @improper:{index} {improper_parameter.k:.10f} {sign:d} {improper_parameter.periodicity:d}"
        )
    for name in atom_types:
        atom_type = params.atom_types[name]
        lines.append(
            f"    pair_coeff @atom:{name} @atom:{name} {atom_type.epsilon:.10f} {atom_type.sigma:.10f}"
        )
    lines.extend(["  }", "}", ""])
    return "\n".join(lines)


def _system_lt_text(structure: Structure, lt_stem: str) -> str:
    """Write the ``system.lt`` assembly mirroring the AuToFF convention."""

    molecule = _molecule_name(structure.name)
    lines = [
        "# Generated by lft",
        f'import "{lt_stem}.lt"',
        "",
        f"mols = new {molecule} [1]",
        "",
        'write_once("Data Boundary") {',
    ]
    lines.extend(f"    {line}" for line in _box_lines(structure))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _image_map(structure: Structure) -> dict[str, Any]:
    def term_payload(term: Any) -> dict[str, Any]:
        positions = []
        for atom_index, image in zip(term.atoms, term.atom_images):
            position = structure.atom(atom_index).position.copy()
            if structure.cell is not None:
                position = position + structure.cell.image_vector(image)
            positions.append([float(value) for value in position])
        return {
            "atoms": list(term.atoms),
            "atom_images": [list(image) for image in term.atom_images],
            "local_positions_angstrom": positions,
        }

    return {
        "schema": "lft.image_map.v1",
        "backend": "lammps",
        "cell": structure.cell.to_dict() if structure.cell else None,
        "bonds": [
            {
                "atoms": [bond.i, bond.j],
                "image_shift": list(bond.image_shift),
                "order": bond.order,
            }
            for bond in structure.bonds
        ],
        "angles": [term_payload(term) for term in structure.angles],
        "dihedrals": [term_payload(term) for term in structure.dihedrals],
        "impropers": [term_payload(term) for term in structure.impropers],
        "pairs": [term_payload(term) for term in structure.pairs],
        "winding": compute_winding(structure),
    }
