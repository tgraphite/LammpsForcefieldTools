"""Multiwfn built-in sphericalized free-atom densities.

The radial density library shipped with Multiwfn (mode 1, the default for
Hirshfeld/CM5/ADCH) is stored as a compressed numpy asset generated by
``scripts/extract_multiwfn_assets.py`` from the reference-only Fortran source.
This module replicates Multiwfn's 4-point Lagrangian interpolation so the
internal population engine reproduces the reference toolchain.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import numpy as np

_ASSET = Path(__file__).resolve().parent / "data" / "multiwfn_atmraddens.npz"


@lru_cache(maxsize=1)
def _load() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    with np.load(_ASSET) as data:
        return (
            np.asarray(data["radial_positions_bohr"], dtype=float),
            np.asarray(data["densities"], dtype=float),
            np.asarray(data["npts"], dtype=int),
        )


def atomic_radial_density(atomic_number: int, r_bohr: float) -> float:
    """Sphericalized free-atom density (e/bohr^3) at distance r_bohr (Bohr)."""
    positions, densities, npts = _load()
    if atomic_number >= len(densities) or atomic_number < 1:
        return 0.0
    count = int(npts[atomic_number])
    return float(_lagrange4_batch(np.atleast_1d(float(r_bohr)), positions[:count], densities[atomic_number, :count])[0])


def atomic_radial_density_vectorized(atomic_number: int, radii_bohr: np.ndarray) -> np.ndarray:
    """Evaluate a single element's free-atom density at a batch of radii."""
    positions, densities, npts = _load()
    z = int(atomic_number)
    radii = np.atleast_1d(np.asarray(radii_bohr, dtype=float))
    if z < 1 or z >= len(densities):
        return np.zeros_like(radii, dtype=float)
    count = int(npts[z])
    return _lagrange4_batch(radii, positions[:count], densities[z, :count])


def _lagrange4_batch(r: np.ndarray, ptpos: np.ndarray, ptval: np.ndarray) -> np.ndarray:
    """Multiwfn ``lagintpol`` with itype=1, vectorized over ``r``.

    4-point Lagrangian value-only interpolation with the reference boundary
    handling: linear extrapolation at the inner edge, zero beyond the outer edge.
    """
    npt = len(ptpos)
    out = np.zeros_like(r, dtype=float)
    inner = r <= ptpos[0]
    if np.any(inner):
        slope = (ptval[1] - ptval[0]) / (ptpos[1] - ptpos[0])
        out[inner] = ptval[0] - (ptpos[0] - r[inner]) * slope
    outer = r >= ptpos[npt - 1]
    out[outer] = 0.0
    mid = ~(inner | outer)
    if not np.any(mid):
        return out
    rm = r[mid]
    i_fortran = np.searchsorted(ptpos, rm, side="right") + 1
    iend = i_fortran + 1
    istart = i_fortran - 2
    low = istart < 1
    istart[low] += 1
    iend[low] += 1
    high = iend > npt
    iend[high] -= 1
    istart[high] -= 1
    nodes = istart[:, None] + np.arange(4) - 1
    node_pos = ptpos[nodes]
    node_val = ptval[nodes]
    numerator = rm[:, None] - node_pos
    value = np.zeros_like(rm)
    for m in range(4):
        other = np.arange(4) != m
        poly = numerator[:, other].prod(axis=1) / (node_pos[:, m][:, None] - node_pos[:, other]).prod(axis=1)
        value += node_val[:, m] * poly
    out[mid] = value
    return out